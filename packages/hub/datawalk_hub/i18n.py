def t(key: str, lang: str = "en", **params: Any) -> str:
    text = CATALOGS.get(lang, {}).get(key) or CATALOGS["en"][key]
    return text.format(**params)


def pick_language(request) -> str:
    """The `lang` query parameter, else the cookie, else the first supported language of
    Accept-Language, else English."""
    for lang in (request.query_params.get("lang"), request.cookies.get(COOKIE)):
        if lang in CATALOGS:
            return lang
    # ponytail: takes Accept-Language in the order sent (browsers sort by q), q values ignored
    for part in request.headers.get("accept-language", "").split(","):
        lang = part.split(";")[0].strip().split("-")[0].lower()
        if lang in CATALOGS:
            return lang
    return "en"


def template_context(request) -> dict[str, Any]:
    """Jinja context processor: `t` in the request's language, and `lang`."""
    lang = pick_language(request)
    return {"t": partial(t, lang=lang), "lang": lang, "languages": list(CATALOGS)}
